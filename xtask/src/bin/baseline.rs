//! Generate `tests-red-baseline.md` from each platform's test output.
//!
//! Usage:
//!   cargo run -p xtask --bin baseline
//!     Runs rust + web suites locally, aggregates outputs, writes the doc.
//!
//!   cargo run -p xtask --bin baseline -- --check
//!     Regenerates into a temp buffer and diffs against the committed copy.
//!     Exits non-zero on drift. Intended for CI.
//!
//! This deliberately owns the aggregation so "are we done yet?" is a `git diff`
//! on a single file, not a doc-update dance across platforms.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn main() {
    if let Err(error) = run() {
        eprintln!("baseline error: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let check_mode = env::args().any(|arg| arg == "--check");
    let strict_mode = check_mode || env::var_os("CI").is_some();
    let workspace = workspace_root()?;
    let output_path = workspace.join("tests-red-baseline.md");

    let report = generate_report(&workspace, strict_mode)?;

    if check_mode {
        // Byte-exact string diff. This assumes LF line endings — CRLF in a
        // Windows checkout would trip the check. CI runs on Linux runners so
        // this is fine for our workflows; if that ever changes, switch to
        // a normalized line-ending compare here.
        let committed = fs::read_to_string(&output_path).unwrap_or_default();
        if committed != report {
            eprintln!("tests-red-baseline.md is out of date — run `cargo run -p xtask --bin baseline`");
            eprintln!("--- committed");
            eprintln!("{committed}");
            eprintln!("--- generated");
            eprintln!("{report}");
            std::process::exit(2);
        }
        println!("tests-red-baseline.md is up to date");
        return Ok(());
    }

    fs::write(&output_path, &report)
        .map_err(|error| format!("failed to write {}: {error}", output_path.display()))?;
    println!("wrote {}", output_path.display());
    Ok(())
}

fn workspace_root() -> Result<PathBuf, String> {
    let manifest = env::var_os("CARGO_MANIFEST_DIR")
        .ok_or("CARGO_MANIFEST_DIR is not set".to_owned())?;
    Path::new(&manifest)
        .parent()
        .map(Path::to_path_buf)
        .ok_or("xtask must live inside the workspace".to_owned())
}

fn generate_report(workspace: &Path, strict: bool) -> Result<String, String> {
    let rust = run_rust_tests(workspace)?;
    let web = run_web_tests(workspace, strict)?;

    let ios_notes = "requires macOS runner with xcodegen + xcodebuild — see ux-tests.yml `ios-unit` job";
    let android_notes = "requires JDK 17 + android SDK — see ux-tests.yml `android-jvm` job";

    let header = "# tests-red-baseline.md\n\
\n\
This file is generated by `cargo run -p xtask --bin baseline`. Do not edit by hand.\n\
\n\
Each platform's suite is run end-to-end; pass/fail/ignored totals land here so\n\
the fix backlog is a `git diff`.\n\
\n\
## How to read changes\n\
\n\
- **passed ↑**: new tests written and passing, or a RED test was fixed.\n\
- **failed ↑**: a new spec gap was tested (good — more coverage), or a regression.\n\
- **failed ↓**: a spec gap was fixed. Verify via the commit that closed it.\n\
- **ignored ↑**: a test was parked with a specific follow-up note (test-harness\n\
  limitation, not a lost test). Search the test source for `#[ignore` to find\n\
  the reason.\n\
- **passed ↓ without a matching failed ↑**: investigate — a test was likely\n\
  deleted or renamed.\n\
\n\
";

    let rust_section = format!(
        "## runtime-core + parity-fixtures (Rust)\n\
- passed: {}\n- failed: {}\n- ignored: {}\n\n",
        rust.passed, rust.failed, rust.ignored
    );
    let web_section = format!(
        "## companion-web (vitest)\n\
- passed: {}\n- failed: {}\n- todo: {}\n\n",
        web.passed, web.failed, web.todo
    );
    let ios_section = format!("## companion-ios (XCTest)\n- status: not run locally ({ios_notes})\n\n");
    let android_section = format!("## companion-android (JVM unit tests)\n- status: not run locally ({android_notes})\n\n");

    Ok(format!(
        "{header}{rust_section}{web_section}{ios_section}{android_section}"
    ))
}

#[derive(Debug, Default)]
struct RustTotals {
    passed: u32,
    failed: u32,
    ignored: u32,
}

fn run_rust_tests(workspace: &Path) -> Result<RustTotals, String> {
    // libtest's JSON output is nightly-only, so we ask for it via the stable
    // `-Z unstable-options`-free path by invoking `cargo test` and parsing the
    // text summary. We parse every test binary's summary line deterministically
    // and trust the `test result: ...` label because libtest has had it for
    // over a decade. Multi-binary runs produce one line per binary; we sum.
    //
    // `--no-fail-fast` ensures a failing test binary does not stop subsequent
    // binaries from running — the baseline wants full aggregate totals, not
    // "first failure aborts".
    let output = Command::new("cargo")
        .args(["test", "-p", "parity-fixtures", "--no-fail-fast"])
        .current_dir(workspace)
        .stderr(Stdio::piped())
        .stdout(Stdio::piped())
        .output()
        .map_err(|error| format!("failed to spawn cargo: {error}"))?;

    let stdout = String::from_utf8_lossy(&output.stdout);
    let mut totals = RustTotals::default();
    for line in stdout.lines() {
        let Some(rest) = line.trim().strip_prefix("test result: ") else { continue };
        // Shape: "ok. 3 passed; 0 failed; 1 ignored; 0 measured; 0 filtered out; finished in 0.01s"
        // Drop the leading "ok." or "FAILED." token.
        let after_tag = rest.splitn(2, '.').nth(1).unwrap_or(rest).trim();
        for field in after_tag.split(';') {
            let trimmed = field.trim();
            let Some((count_str, label)) = trimmed.split_once(' ') else { continue };
            let Ok(count) = count_str.parse::<u32>() else { continue };
            match label {
                "passed" => totals.passed += count,
                "failed" => totals.failed += count,
                "ignored" => totals.ignored += count,
                _ => {}
            }
        }
    }
    Ok(totals)
}

#[derive(Debug, Default)]
struct WebTotals {
    passed: u32,
    failed: u32,
    todo: u32,
}

fn run_web_tests(workspace: &Path, strict: bool) -> Result<WebTotals, String> {
    let companion_web = workspace.join("companion-web");
    if !companion_web.join("node_modules").exists() {
        if strict {
            return Err(
                "companion-web/node_modules is missing — run `npm ci` in companion-web before \
                 `cargo run -p xtask --bin baseline` (or run CI with the install step)"
                    .to_owned(),
            );
        }
        return Ok(WebTotals::default());
    }
    // Use vitest's JSON reporter so we never have to keep up with label wording.
    // Note: vitest exits non-zero when any test fails. That's expected for a
    // red baseline — we still want to read the JSON summary and report the
    // counts. Only the absence of the summary file is a real error.
    //
    // We invoke via `npm run test:baseline` so the command is coupled to
    // package.json scripts; if anyone adds a flag (coverage, filters) to the
    // vitest script, baseline stays aligned.
    let _ = Command::new("npm")
        .args(["run", "--silent", "test:baseline"])
        .current_dir(&companion_web)
        .stderr(Stdio::piped())
        .stdout(Stdio::piped())
        .output()
        .map_err(|error| format!("failed to spawn npm run test:baseline: {error}"))?;

    let summary_path = companion_web.join(".vitest/summary.json");
    let text = fs::read_to_string(&summary_path).map_err(|error| {
        format!(
            "failed to read {}: {error}. Run `cd companion-web && npm run test:baseline` first.",
            summary_path.display()
        )
    })?;
    Ok(parse_vitest_json(&text))
}

fn parse_vitest_json(text: &str) -> WebTotals {
    // Vitest JSON shape: { numPassedTests, numFailedTests, numTodoTests, ... }
    let mut totals = WebTotals::default();
    totals.passed = read_json_u32(text, "numPassedTests").unwrap_or(0);
    totals.failed = read_json_u32(text, "numFailedTests").unwrap_or(0);
    totals.todo = read_json_u32(text, "numTodoTests").unwrap_or(0);
    totals
}

fn read_json_u32(text: &str, key: &str) -> Option<u32> {
    let needle = format!("\"{key}\":");
    let start = text.find(&needle)?;
    let after = &text[start + needle.len()..];
    let end = after
        .find(|c: char| c == ',' || c == '}')
        .unwrap_or(after.len());
    after[..end].trim().parse().ok()
}
